    alpha2      char(2) PRIMARY KEY,
    alpha3      char(3) NOT NULL,
    numeric_code char(3),
    name_pt     text NOT NULL,
    name_en     text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_country_name_pt ON country (name_pt);

